/**
 * Shared schedule expression types for scheduled conversation runs.
 * The `cron` variant is preserved because it models the expression kind,
 * not the product feature name.
 */
export type ScheduleSpec =
  | { kind: 'at'; atMs: number; description: string }
  | { kind: 'every'; everyMs: number; description: string }
  | { kind: 'cron'; expr: string; tz?: string; description: string };
